export function fullName(person: Person): string {
  return [person.firstName, person.middleName, person.lastName].filter(Boolean).join(' ')
}

export function initials(person: Person): string {
  return `${person.firstName[0]}${person.lastName[0]}`
}

export function age(person: Person): number | null {
  if (!person.birthYear) return null
  const endYear = person.deathYear ?? new Date().getFullYear()
  return endYear - person.birthYear
}

export function avatarColor(person: Person): string {
  const colors: Record<number, string> = {
    0: '#6E4828',
    1: '#8B5E3C',
    2: '#A67B52',
    3: '#C49A78',
  }
  return colors[person.generation] ?? '#8B5E3C'
}

